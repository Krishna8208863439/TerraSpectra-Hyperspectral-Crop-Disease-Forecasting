// ── Complete Normalizer for Diagnosis Result ────────────────────────────────
export function localizeDiagnosisResult(result, language) {
  if (!result || typeof result !== "object") return result;
  if (language !== "mr") return result;

  // Localize Crop
  let localizedCrop = result.crop || "";
  const cropLower = String(localizedCrop).toLowerCase().trim();
  for (const [key, mrVal] of Object.entries(CROP_NAMES_MR)) {
    if (cropLower.includes(key)) {
      localizedCrop = mrVal;
      break;
    }
  }

  // Localize Disease / Diagnosis
  let localizedDiagnosis = result.diagnosis || result.disease || "";
  const diagLower = String(localizedDiagnosis).toLowerCase().trim();
  for (const [key, mrVal] of Object.entries(DISEASE_NAMES_MR)) {
    if (diagLower.includes(key) || key.includes(diagLower)) {
      localizedDiagnosis = mrVal;
      break;
    }
  }
  if (!localizedDiagnosis || localizedDiagnosis === result.diagnosis) {
    localizedDiagnosis = translateAgronomicTextToMarathi(localizedDiagnosis);
  }

  // Localize Symptoms
  let localizedSymptoms = [];
  if (Array.isArray(result.symptoms)) {
    localizedSymptoms = result.symptoms.map(s => translateAgronomicTextToMarathi(s));
  } else if (typeof result.symptoms === "string") {
    localizedSymptoms = [translateAgronomicTextToMarathi(result.symptoms)];
  }

  // Localize Treatment
  let localizedTreatment = [];
  if (Array.isArray(result.treatment)) {
    localizedTreatment = result.treatment.map(t => translateAgronomicTextToMarathi(t));
  } else if (typeof result.treatment === "string") {
    localizedTreatment = [translateAgronomicTextToMarathi(result.treatment)];
  }

  // Localize Fertilizer Advice
  let localizedFertilizer = result.fertilizerAdvice;
  if (Array.isArray(result.fertilizerAdvice)) {
    localizedFertilizer = result.fertilizerAdvice.map(f => translateAgronomicTextToMarathi(f));
  } else if (typeof result.fertilizerAdvice === "string") {
    localizedFertilizer = translateAgronomicTextToMarathi(result.fertilizerAdvice);
  }

  // Localize Irrigation Advice
  let localizedIrrigation = result.irrigationAdvice
    ? translateAgronomicTextToMarathi(result.irrigationAdvice)
    : "पिकाच्या वाढीच्या टप्प्यानुसार नियमित पाणी पुरवठा चालू ठेवा.";

  // Localize Prevention Tips
  let localizedPrevention = [];
  if (Array.isArray(result.prevention)) {
    localizedPrevention = result.prevention.map(p => translateAgronomicTextToMarathi(p));
  } else if (typeof result.prevention === "string") {
    localizedPrevention = [translateAgronomicTextToMarathi(result.prevention)];
  }

  // Localize Severity
  const sevLower = String(result.severity || "medium").toLowerCase();
  const localizedSeverity = sevLower === "high"
    ? "उच्च धोका (High)"
    : sevLower === "low"
      ? "कमी धोका (Low)"
      : "मध्यम धोका (Medium)";

  // Localize Provider
  const localizedProvider = language === "mr"
    ? "ॲग्रीएक्सपर्ट एआय व्हिजन निदान"
    : (result.provider || "AgriExpert AI Vision");

  // Localize Disclaimer
  const localizedDisclaimer = "एआय आधारित मूल्यांकन; प्रत्यक्ष शेतात खात्री करण्यासाठी स्थानिक कृषी विज्ञान केंद्र (KVK) चा सल्ला घ्या.";

  return {
    ...result,
    crop: localizedCrop,
    diagnosis: localizedDiagnosis,
    disease: localizedDiagnosis,
    symptoms: localizedSymptoms,
    treatment: localizedTreatment,
    fertilizerAdvice: localizedFertilizer,
    irrigationAdvice: localizedIrrigation,
    prevention: localizedPrevention,
    severityDisplay: localizedSeverity,
    provider: localizedProvider,
    disclaimer: localizedDisclaimer
  };
}
